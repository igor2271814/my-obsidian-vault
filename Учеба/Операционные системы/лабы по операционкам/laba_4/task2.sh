#!/bin/bash



INTERVAL=3
COUNT=4
OUTPUT_DIR="./"


TIMESTAMP=$(date +"%Y-%m-%d_%H:%M:%S")
OUTPUT_FILE="${OUTPUT_DIR}${TIMESTAMP}_syslog.txt"

for cmd in mpstat pidstat; do
    if ! command -v $cmd &> /dev/null; then
        echo "Ошибка: команда '$cmd' не найдена!"
        echo "Установите пакет: sudo apt install sysstat"
        exit 1
    fi
done


echo "Начало сбора статистики..."
echo "Интервал: ${INTERVAL} сек"
echo "Отчётов: ${COUNT}"
echo "Файл: ${OUTPUT_FILE}"
echo ""


{
    echo "============================================================================="
    echo "  СИСТЕМНЫЙ ОТЧЁТ: ${TIMESTAMP}"
    echo "  Хост: $(hostname)"
    echo "  Ядро: $(uname -r)"
    echo "  Дата сбора: $(date)"
    echo "============================================================================="
    echo ""
    
    
    echo "-----------------------------------------------------------------------------"
    echo "  1. ОБЩАЯ ИНФОРМАЦИЯ О СИСТЕМЕ"
    echo "-----------------------------------------------------------------------------"
    echo "Количество ядер CPU: $(nproc)"
    echo "Всего памяти: $(free -h | awk '/^Mem:/{print $2}')"
    echo "Свободно памяти: $(free -h | awk '/^Mem:/{print $7}')"
    echo "Время безотказной работы: $(uptime -p)"
    echo ""
    
    
    echo "-----------------------------------------------------------------------------"
    echo "  2. СТАТИСТИКА ИСПОЛЬЗОВАНИЯ ПРОЦЕССОРОВ (mpstat)"
    echo "-----------------------------------------------------------------------------"
    echo "Все процессоры:"
    mpstat -P ALL ${INTERVAL} ${COUNT}
    echo ""
    
    
    echo "-----------------------------------------------------------------------------"
    echo "  3. СТАТИСТИКА ПРОЦЕССОВ (pidstat) - CPU"
    echo "-----------------------------------------------------------------------------"
    pidstat -u ${INTERVAL} ${COUNT}
    echo ""
    
    echo "-----------------------------------------------------------------------------"
    echo "  4. СТАТИСТИКА ПРОЦЕССОВ (pidstat) - ПАМЯТЬ"
    echo "-----------------------------------------------------------------------------"
    pidstat -r ${INTERVAL} ${COUNT}
    echo ""
    
    echo "-----------------------------------------------------------------------------"
    echo "  5. СТАТИСТИКА ПРОЦЕССОВ (pidstat) - ДИСКОВЫЙ I/O"
    echo "-----------------------------------------------------------------------------"
    pidstat -d ${INTERVAL} ${COUNT} 2>/dev/null || echo "Данные недоступны (требуются права root)"
    echo ""
    
    
    echo "-----------------------------------------------------------------------------"
    echo "  4. ЗАВЕРШЕНИЕ СБОРА ДАННЫХ"
    echo "-----------------------------------------------------------------------------"
    echo "Время окончания: $(date)"
    echo "============================================================================="
    
} > "${OUTPUT_FILE}"


echo "Сбор статистики завершён!"
echo "Файл сохранён: ${OUTPUT_FILE}"
echo "Размер файла: $(du -h ${OUTPUT_FILE} | cut -f1)"
echo ""


echo "Последние 10 строк отчёта:"
tail -n 10 "${OUTPUT_FILE}"
